const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required', '--use-gl=swiftshader', '--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = [];
  page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
  page.on('pageerror', e => errs.push('pageerror: ' + e.message + '\n' + (e.stack || '')));
  await page.goto('file://' + path.resolve('dist/dweller.html'));
  await page.waitForFunction(() => window.__dweller, null, { timeout: 15000 });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: 'shots/title.png' });
  await page.keyboard.press('Space');
  await page.waitForTimeout(800);
  await page.keyboard.down('KeyD');
  await page.waitForTimeout(1600);
  await page.keyboard.press('Space');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'shots/play0.png' });
  await page.keyboard.up('KeyD');
  const st = await page.evaluate(() => { const s = window.__dweller.state; return { x: s.x, y: s.y, dead: s.dead, mode: window.__dweller.mode }; });
  console.log('state', JSON.stringify(st));
  console.log('errors', errs.length ? errs.join('\n') : 'none');
  await browser.close();
})();
